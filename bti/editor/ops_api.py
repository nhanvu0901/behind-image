"""HTTP layer of the typed operations (`bti/ops/`): two batch routes, the change log, undo and the schema.

    POST /api/projects/{pid}/picks/ops                  a batch of picks operations
    POST /api/projects/{pid}/storyboard/ops             a batch of storyboard operations
    GET  /api/projects/{pid}/changes?doc=&limit=        the change log, newest first
    POST /api/projects/{pid}/changes/{batch}/undo       undo one batch
    GET  /api/ops/schema                                every operation: summary, JSON Schema, example

Everything of substance is in `bti.ops` (no HTTP in it); this module reads the JSON body, hands it to the runner with the adapter
of the document, and turns a typed `OpError` into the existing `ApiError` (`{detail, code, fix, retry, fields?, ...}`).
Mounted by `create_app`, which gives it the app's own helpers: the storyboard lock, the project's engine object, the saved
storyboard and the function that forgets the caches of a project, so that a batch writes the storyboard exactly where, under the
lock and through the files the page's PUT does. The documentation is `docs/OPS.md`, generated by `python -m bti.ops.doc`.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Callable

from fastapi import APIRouter, Request
from starlette.concurrency import run_in_threadpool

from bti.engine.errors import DataError
from bti.ops import registry, runner
from bti.ops.adapters import PicksAdapter, StoryboardAdapter
from bti.ops.errors import ERRORS, OpError
from bti.ops.log import ChangeLog
from bti.script.store import DocumentCorrupt, ProjectGone

from .common import ApiError, scrub_paths


def to_api(e: OpError) -> ApiError:
    return ApiError(e.status, e.detail, **e.body())


def _from_helper(e: ApiError) -> ApiError:
    """An error of one of the app's own helpers (unknown project, no storyboard, damaged file) gets the same `code`, `fix` and
    `retry` every other error of these routes has."""
    if "code" in e.extra:
        return e
    if e.status == 404 and e.detail == "project not found":
        code = "project_not_found"
    elif e.status == 404 and e.detail == "storyboard not found":
        code = "storyboard_not_found"
    elif e.status == 409 and e.extra.get("corrupt"):
        code = "document_corrupt"
    else:
        return e
    spec = ERRORS[code]
    return ApiError(e.status, e.detail, **{"code": code, "fix": spec[2], "retry": spec[1], **e.extra})


def make_router(root: Path, *, pdir: Callable, project: Callable, saved_storyboard: Callable, slock: Callable,
                forget: Callable) -> APIRouter:
    """`pdir(pid)`, `project(pid)`, `saved_storyboard(pid)`, `slock(pid)` and `forget(pid)` are the app's own helpers (404 for an
    unknown project or a missing storyboard, 409 for a damaged file, the storyboard lock, and the function that drops what the app
    cached about a project's storyboard after a write)."""
    router = APIRouter()

    def guarded(fn: Callable[[], Any]) -> Any:
        try:
            return fn()
        except OpError as e:
            raise to_api(e)
        except ApiError as e:
            raise _from_helper(e)
        except ProjectGone:
            raise to_api(OpError("project_not_found", "project not found"))
        except DocumentCorrupt as e:
            raise to_api(OpError("document_corrupt", str(e), data_error=getattr(e, "what", "script")))
        except DataError as e:                  # the project's own data is unusable (a missing or damaged timing file, an unknown style)
            raise to_api(OpError("document_corrupt", scrub_paths(e.message), data_error=e.what))

    async def body_of(request: Request) -> Any:
        raw = await request.body()
        try:
            return json.loads(raw)
        except (ValueError, RecursionError):
            raise to_api(OpError("invalid_request", "The request body is not valid JSON.",
                                 fields=[{"path": "", "problem": "must be a JSON object"}]))

    def storyboard_adapter(pid: str) -> StoryboardAdapter:
        return StoryboardAdapter(pid, pdir(pid), project=project, saved=saved_storyboard, slock=slock, forget=forget)

    @router.get("/api/ops/schema")
    def ops_schema():
        return registry.schema_document()

    @router.post("/api/projects/{pid}/picks/ops")
    async def picks_ops(pid: str, request: Request):
        body = await body_of(request)

        def work():
            d = pdir(pid)
            return runner.run_batch(PicksAdapter(d), body, ChangeLog(d))
        return await run_in_threadpool(guarded, work)

    @router.post("/api/projects/{pid}/storyboard/ops")
    async def storyboard_ops(pid: str, request: Request):
        body = await body_of(request)

        def work():
            d = pdir(pid)
            return runner.run_batch(storyboard_adapter(pid), body, ChangeLog(d))
        return await run_in_threadpool(guarded, work)

    @router.get("/api/projects/{pid}/changes")
    def changes(pid: str, request: Request):
        def work():
            d = pdir(pid)
            return runner.list_changes(ChangeLog(d), request.query_params.get("doc"), request.query_params.get("limit"))
        return guarded(work)

    @router.post("/api/projects/{pid}/changes/{batch}/undo")
    async def undo(pid: str, batch: str, request: Request):
        body = await body_of(request)

        def work():
            d = pdir(pid)
            adapters = {"picks": PicksAdapter(d), "storyboard": storyboard_adapter(pid)}
            return runner.run_undo(adapters, batch, body, ChangeLog(d))
        return await run_in_threadpool(guarded, work)

    return router
