"""Writes `docs/OPS.md`: the documentation of the operations, generated from the registry (nothing in it is typed by hand twice).

    python -m bti.ops.doc            write docs/OPS.md
    python -m bti.ops.doc --check    exit 1 when the file on disk differs from what the registry says

A test fails when the file is out of date, so a new operation, a new field or a new error code cannot reach the repository
without its documentation.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from . import picks_ops, sb_ops  # noqa: F401  - importing them registers the operations
from . import registry, schemacheck
from .batch import ACTOR_FORMS, MAX_NOTE, MAX_OPS
from .errors import ERRORS
from .log import COPIES_KEEP, RECORDS_KEEP
from .undo import UNDO_SENTENCES

OPS_MD = Path(__file__).resolve().parents[2] / "docs" / "OPS.md"

INTRO = """# Typed operations for the picks and the storyboard

<!-- Generated by `python -m bti.ops.doc` from the registry in bti/ops/. Do not edit this file: change the registry and run the command. -->

Every change to the picks (step 4, `picks.json`) and to the storyboard (step 5, `storyboard.json`) can be made with small
**named operations** instead of rewriting the whole file. Operations are sent in **batches**: the server checks the whole batch
before it writes anything, applies it all or not at all, records it in a change log, and can undo it. The page, an instruction
box, an agent in the app and an agent in a terminal use the same operations.

Every example below is written for the test fixture project (shots `s0001` to `s0010`, assets `A` to `D`, narration lines `b0001`
to `b0006`); it passes its own schema and applies to that project. `GET /api/ops/schema` gives the same schemas and examples as
JSON.

## Routes

| Method and path | What it does |
|---|---|
| `POST /api/projects/{pid}/picks/ops` | Apply a batch of picks operations. |
| `POST /api/projects/{pid}/storyboard/ops` | Apply a batch of storyboard operations. |
| `GET /api/projects/{pid}/changes?doc=picks\\|storyboard&limit=50` | The change log, newest batch first, without the copies of the documents. `doc` is optional (both documents), `limit` is 1 to 200 (default 50). Answer: `{"changes": [record, ...]}`. |
| `POST /api/projects/{pid}/changes/{batch}/undo` | Undo one batch. Body: `{"base_rev", "actor", "note"?}`. Answer: like a batch, plus `undo_of`. |
| `GET /api/ops/schema` | `{"picks": {op: {summary, schema, example}}, "storyboard": {...}}`. |

## The batch request

```json
{
  "base_rev": "<the revision you read>",
  "actor": "agent:gemini-3.8-flash",
  "ops": [ {"op": "...", "...": "..."} ],
  "dry_run": false,
  "scope": null,
  "note": ""
}
```

| Field | Meaning |
|---|---|
| `base_rev` | The revision of the document you read (`rev` of `GET /api/projects/{pid}` for the storyboard, of `GET /api/projects/{pid}/picks` for the picks). A batch for any other revision is refused with `stale_revision` and nothing is written. |
| `actor` | Who sends it, one of: %(actors)s. Kept in the log; an item written by a batch gets `source: "human"` for `human`, `source: "agent"` for the others. |
| `ops` | 1 to %(max_ops)d operations, applied in order. An operation sees what the earlier ones did. |
| `dry_run` | `true`: check everything and describe the changes, write nothing (the file on disk is byte-identical). An import is only checked for shape in a dry run, nothing is downloaded. |
| `scope` | `null`, or exactly one of `{"shots": [ids]}`, `{"chapters": [ids]}`, `{"beats": [ids]}`. An operation that touches anything outside it refuses the whole batch with `out_of_scope`. For the storyboard a shot is in a chapter or beat when it starts inside it; for the picks `beats` and `chapters` name narration lines, and operations that change something shared by every line (`set_main`, `set_region`, `remove_region`, an import with `as_main`) are outside any scope. A shot made by `split_shot` or `replace_range` from shots in scope is in scope. |
| `note` | Free text kept in the log, up to %(max_note)d characters (for example the owner's request). |

Any other field is refused (`invalid_request`).

## The answer

```json
{
  "rev": "<revision after the batch>",
  "applied": 2,
  "batch": "batch_0007",
  "dry_run": false,
  "changes": [{"target": {"shot": "s0012"}, "time": "1:42", "what": "Cảnh 12: đổi kỹ thuật sang Zoom chậm"}],
  "issues": [],
  "created": {"shots": [], "overlays": [], "assets": [], "refs": {}}
}
```

- `batch` is the id in the change log; it is `null` for a dry run and for a batch that leaves the document as it was (nothing is written or logged then and `rev` is the revision it was). An operation that changed nothing when it ran has no entry in `changes`.
- `rev` is the revision after the write. For a dry run it is the current revision.
- `changes` has one entry per effect, in plain Vietnamese. `target` is `{"shot"}` (with `"overlay"` for an overlay), `{"beat"}` or `{"asset"}`; `time` is `m:ss` where the thing has a place in time, else `null`. In a dry run the asset of an import has no key yet: its target is `{"asset": null}`.
- `issues` are the validation issues of the resulting document (errors that were already there and warnings stay).
- `created` lists the ids the batch made: `shots`, `overlays` (`{shot, overlay}`), `assets`, and `refs` (name to id).

### Refs

An operation that creates something (`import`, `split_shot`, `add_overlay`, and a new shot of `replace_range`) can carry `"ref": "name"`. Any later field that names an asset, a shot or an overlay may then say `"$name"` instead of the id. Ids made by a batch are also deterministic: a new shot is `s` and one more than the largest shot number, padded to four digits; a new overlay is `o` and one more than the largest overlay number of the storyboard.

### All or nothing, and validation

If any operation is refused, nothing is written. After the operations, the document goes through the validation the existing save uses. An error that is **new** (not already in the document before the batch, found by its code and its place, by shot and overlay id) refuses the batch with `validation_failed`, with the issues and, for each, `op_index` of the operation that changed the shot it is about when that can be told. Problems that were already there before the batch never block it.

### Locks

A locked shot (or overlay) refuses every operation on it, whoever the actor is, except `unlock` (`locked`). `lock` on something already locked is refused too.

### What an approved document does when a batch changes it

A batch saves a document exactly as the page's own save does.

- **Storyboard** (`PUT /api/projects/{pid}/storyboard`): the `approvals` record is kept as it is; because the revision changed, the approval names an older revision and no longer stands, and the storyboard must be approved again. The previous file is copied to `history/`.
- **Picks** (`PUT /api/projects/{pid}/picks`): saving a document whose revision changed drops its approval, and the previous file is kept as `picks.prev.json`; the picks must be approved again. An undo that gives back exactly the content that was approved gives the approval back with it.

### The change log and undo

Every batch that wrote a document is one record in `projects/{pid}/changes/` (next to `history/`): `batch`, `doc`, `time`, `actor`, `note`, `ops` (as sent), `applied`, `changes`, `created`, `rev_before`, `rev_after`, `touched`, `undo_of`, `scope`, `copies`, and, in files of their own, the document before and after. The newest %(records)d records of each document are kept; only the newest %(copies)d keep their copies (an older record is still listed, with `copies: false`, but cannot be undone: `undo_unavailable`). Pages' own saves (`PUT`) are not logged.

An undo puts back what the batch changed, and nothing else: each thing the batch changed (a shot; for the picks the main picture, a line, the regions of an asset, an asset) is compared with the batch's own copy of what it left. When all of them are still as the batch left them, each goes back to its value before the batch. When one was changed since, by a later batch or by a save of the page, nothing is undone: `undo_conflict` names the things and, when the log knows them, the later batches (`conflicts: [{thing, key, batches}]`). The newest batch of a document can be undone unless the page itself changed what it touched. An undo is a batch of the log (`undo_of`), so it can be undone.

## Errors

Every error body has `code`, `detail` (one English sentence), `fix` (one English imperative sentence an agent can act on) and `retry` (`no`, `after_fix` or `later`). When a field is wrong it has `fields: [{"path": "ops[1].params.region", "problem": "...", "allowed": [...]}]` (`allowed` whenever the set is small: region names, technique ids, slot names, enum values), and `op_index` names the operation. The `fix` below is the canonical sentence; a route may sharpen it for the case.

| Code | Status | Retry | Meaning | Fix |
|---|---|---|---|---|
"""


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _errors_table() -> str:
    rows = []
    for code, (status, retry, fix, meaning) in ERRORS.items():
        rows.append("| `%s` | %d | `%s` | %s | %s |" % (code, status, retry, _cell(meaning), _cell(fix)))
    return "\n".join(rows) + "\n"


def _fields_table(schema: dict) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = ["| Field | Type | Required | Meaning |", "|---|---|---|---|"]
    for name, sub in props.items():
        desc = sub.get("description") or ""
        if "anyOf" in sub and not desc:
            desc = sub["anyOf"][0].get("description", "")
        rows.append("| `%s` | %s | %s | %s |" % (name, _cell(schemacheck.describe_type(sub)), "yes" if name in required else "no", _cell(desc)))
    return "\n".join(rows) + "\n"


def _op_section(d) -> str:
    out = ["### `%s`\n" % d.name, d.summary + "\n", _fields_table(d.schema),
           "Example:\n", "```json\n%s\n```\n" % json.dumps(d.example, indent=2, ensure_ascii=False)]
    if len(d.sentences) == 1:
        out.append("Sentence in `changes`: `%s`\n" % next(iter(d.sentences.values())))
    else:
        out.append("Sentences in `changes`: %s\n" % "; ".join("`%s` = `%s`" % (k, v) for k, v in d.sentences.items()))
    return "\n".join(out)


def render() -> str:
    intro = INTRO % {"actors": ", ".join("`%s`" % a for a in ACTOR_FORMS), "max_ops": MAX_OPS, "max_note": MAX_NOTE,
                     "records": RECORDS_KEEP, "copies": COPIES_KEEP}
    parts = [intro + _errors_table()]
    parts.append("\n## Picks operations\n")
    parts.append("The document is `picks.json` (schema `bti.picks/1`): `main_asset`, `assets` (with `regions`), and per narration line `beats` "
                 "with `items` (`asset`, `region`, `role`, `note`), `status` and `note`. A line with no pictures shows the main picture again.\n")
    parts.extend(_op_section(d) for d in registry.defs("picks").values())
    parts.append("\n## Storyboard operations\n")
    parts.append("The document is `storyboard.json` (schema `bti.storyboard/1`). A shot lasts from its `start` to the `start` of the next shot "
                 "(the last one to `end`); an anchor is `{\"t\": seconds}` or `{\"w\": word index, \"off\": seconds}`. A time given as a number "
                 "of seconds is snapped to a word start within 0.35 s unless `snap` is false, as the page does.\n")
    parts.extend(_op_section(d) for d in registry.defs("storyboard").values())
    parts.append("\n## Sentences of an undo\n")
    parts.append("An undo describes what it put back with these sentences (`changes` of the undo batch):\n")
    for doc, table in UNDO_SENTENCES.items():
        parts.append("- %s: %s" % (doc, "; ".join("`%s`: %s" % (k, v) for k, v in table.items())))
    text = "\n".join(parts).rstrip("\n") + "\n"
    return text


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    text = render()
    if "--check" in argv:
        current = OPS_MD.read_text(encoding="utf-8") if OPS_MD.is_file() else ""
        if current != text:
            print("docs/OPS.md is out of date: run python -m bti.ops.doc", file=sys.stderr)
            return 1
        return 0
    OPS_MD.parent.mkdir(parents=True, exist_ok=True)
    with open(OPS_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (OPS_MD, len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
