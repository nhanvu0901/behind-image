"""Server-side audio assembly: atempo voice, cut per beat, place on the final timeline, synth music pad, mix, two-pass loudnorm."""
import json, os, subprocess, sys, wave, re
import numpy as np
W = os.environ.get("BENCH_W", r"D:\bench\claude_code")
spec = json.load(open(os.path.join(W, "audio_spec2.json")))
at = spec["atempo"]; END = spec["end"]; SR = 48000

def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: print(r.stderr[-2000:]); raise SystemExit(1)
    return r.stderr

V = {}
for g in sorted({sg["wav"] for sg in spec["segments"]}):
    out_ = os.path.join(W, g.replace(".wav", "_fast.wav"))
    run(["ffmpeg", "-y", "-v", "error", "-i", os.path.join(W, g), "-af", "atempo=%.4f" % at, "-ar", str(SR), "-ac", "1", out_])
    with wave.open(out_) as wf:
        assert wf.getframerate() == SR and wf.getsampwidth() == 2
        V[g] = np.frombuffer(wf.readframes(wf.getnframes()), np.int16).astype(np.float32) / 32768.0
def box(x, n):
    x = x.astype(np.float64); c = np.cumsum(np.concatenate([np.zeros(n // 2 + 1), x, np.zeros(n - n // 2 - 1)]))
    return ((c[n:n + len(x)] - c[:len(x)]) / n).astype(np.float32)
N = int((END + 1.0) * SR)
voice = np.zeros(N, np.float32)
fade = int(0.008 * SR)
for sgm in spec["segments"]:
    a = int(sgm["raw_start"] / at * SR); b = int(sgm["raw_end"] / at * SR)
    seg = V[sgm["wav"]][a:b].copy()
    seg[:fade] *= np.linspace(0, 1, fade); seg[-fade:] *= np.linspace(1, 0, fade)
    o = int(sgm["final_start"] * SR)
    voice[o:o + len(seg)] += seg[:max(0, min(len(seg), N - o))]
# ---- music: locally synthesised soft pad (Am - F - C - G drones, detuned sines, slow LFO) + faint room tone. No external sample used.
t = np.arange(N) / SR
chords = [(110.0, 130.81, 164.81), (87.31, 130.81, 174.61), (130.81, 164.81, 196.0), (98.0, 146.83, 196.0)]
clen = 10.0
pad = np.zeros((2, N), np.float32)
for ch in range(2):
    for ci in range(int(END / clen) + 3):
        c0 = ci * clen - 1.5; c1 = c0 + clen + 3.0
        i0, i1 = max(0, int(c0 * SR)), min(N, int(c1 * SR))
        if i1 <= i0: continue
        tt = t[i0:i1]
        env = np.clip(np.minimum((tt - c0) / 3.0, (c1 - tt) / 3.0), 0, 1) ** 1.5
        sig = np.zeros_like(tt)
        for f in chords[ci % 4]:
            for det, amp in ((0.0, 1.0), (0.37 if ch else -0.37, 0.7)):
                sig += amp * np.sin(2 * np.pi * (f + det) * tt) + .25 * amp * np.sin(2 * np.pi * 2 * (f + det) * tt) + .08 * amp * np.sin(2 * np.pi * 3 * (f + det) * tt)
        pad[ch, i0:i1] += (sig * env).astype(np.float32)
lfo = 0.75 + 0.25 * np.sin(2 * np.pi * t / 11.0)
pad *= lfo[None, :].astype(np.float32)
rng = np.random.RandomState(3)
nz = rng.normal(0, 1, (2, N)).astype(np.float32)
k = np.ones(400, np.float32) / 400
nz = np.stack([box(nz[c], 400) for c in range(2)])   # low-passed noise = room tone
pad = pad / (np.sqrt((pad ** 2).mean()) + 1e-9) * 0.05 + nz / (np.sqrt((nz ** 2).mean()) + 1e-9) * 0.006
fin = int(2.0 * SR); pad[:, :fin] *= np.linspace(0, 1, fin); pad[:, -fin:] *= np.linspace(1, 0, fin)
vr = np.sqrt((voice[np.abs(voice) > 0.01] ** 2).mean())
# music about 24 dB under voice RMS, plus a gentle duck (-4 dB) while narration is active
active = box((np.abs(voice) > 0.02).astype(np.float32), int(.4 * SR))
duck = 1 - 0.37 * np.clip(active * 3, 0, 1)
mus = pad / (np.sqrt((pad ** 2).mean())) * vr * 10 ** (-24 / 20) * duck[None, :]
mix = np.stack([voice, voice]) + mus
mix = np.clip(mix, -1, 1)
out = os.path.join(W, "mix2_pre.wav")
with wave.open(out, "wb") as wf:
    wf.setnchannels(2); wf.setsampwidth(2); wf.setframerate(SR)
    wf.writeframes((mix.T * 32767).astype(np.int16).tobytes())
print("voice_rms_db %.1f music_rms_db %.1f" % (20 * np.log10(vr), 20 * np.log10(np.sqrt((mus ** 2).mean()) + 1e-9)))
# ---- two-pass loudnorm to -15 LUFS, TP <= -1.5 dBTP
LN = "loudnorm=I=-15:TP=-1.5:LRA=11"
err = run(["ffmpeg", "-y", "-hide_banner", "-i", out, "-af", LN + ":print_format=json", "-f", "null", "-"])
j = json.loads(err[err.rindex("{"):err.rindex("}") + 1])
af = LN + ":measured_I=%s:measured_TP=%s:measured_LRA=%s:measured_thresh=%s:offset=%s:linear=true:print_format=summary" % (
    j["input_i"], j["input_tp"], j["input_lra"], j["input_thresh"], j["target_offset"])
run(["ffmpeg", "-y", "-v", "error", "-i", out, "-af", af, "-ar", str(SR), "-c:a", "pcm_s16le", os.path.join(W, "mix2_final.wav")])
json.dump({"pass1": j, "pass2_filter": af, "music": "numpy-synthesised pad (Am-F-C-G sines) + low-passed noise room tone, generated by audio_job.py; -24 dB re voice, ducked -4 dB under speech"},
          open(os.path.join(W, "audio_stats2.json"), "w"), indent=1)
print("AUDIO_OK")
